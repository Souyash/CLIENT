                const btn = document.getElementById(`btnDossier${i}`);
                if (btn) {
                    if (i === idx) {
                        btn.className = "w-full text-left p-5 rounded-2xl transition-all duration-300 flex items-center gap-5 border bg-slate-950 border-slate-950 text-white shadow-xl scale-[1.02]";
                    } else {
                        btn.className = "w-full text-left p-5 rounded-2xl transition-all duration-300 flex items-center gap-5 border bg-[#FBFBFC] border-slate-100 text-slate-900 hover:bg-slate-50";
                    }
                }
            }

            const d = dossierData[idx];
            document.getElementById('dossierTag').textContent = d.tag;
            document.getElementById('dossierTitle').textContent = d.title;
            document.getElementById('dossierBadge').textContent = d.badge;
            document.getElementById('dossierQuote').textContent = d.quote;

            const ul = document.getElementById('dossierBullets');
            ul.innerHTML = '';
            d.bullets.forEach(b => {
                const li = document.createElement('li');
                li.className = "flex items-start gap-3 text-slate-600 text-sm md:text-base font-light leading-relaxed";
                li.innerHTML = `<i class="fas fa-check-circle text-emerald-600 mt-1 shrink-0"></i><span>${b}</span>`;
                ul.appendChild(li);
            });
        }

